# =====================================================
# CountVectorizer
# =====================================================

st.header("🔤 CountVectorizer")

st.info(
"""
**CountVectorizer** converts movie descriptions into a Bag-of-Words representation.

Each movie is represented as a vector containing the frequency of every word.
Recommendations are generated by comparing these vectors using **Cosine Similarity**.
"""
)

col1, col2 = st.columns(2)

with col1:

    st.metric(
        "Model Type",
        "Bag of Words"
    )

    st.metric(
        "Similarity",
        "Cosine"
    )

with col2:

    st.metric(
        "Speed",
        "Very Fast"
    )

    st.metric(
        "Semantic Understanding",
        "Low"
    )

st.success("✅ Best suited for small datasets and fast recommendations.")

st.divider()

# =====================================================
# TF-IDF
# =====================================================

st.header("📄 TF-IDF")

st.info(
"""
**TF-IDF (Term Frequency–Inverse Document Frequency)** improves upon CountVectorizer
by reducing the influence of common words while emphasizing informative terms.

This generally produces more meaningful recommendations than simple word counts.
"""
)

col1, col2 = st.columns(2)

with col1:

    st.metric(
        "Model Type",
        "Weighted BoW"
    )

    st.metric(
        "Similarity",
        "Cosine"
    )

with col2:

    st.metric(
        "Speed",
        "Fast"
    )

    st.metric(
        "Semantic Understanding",
        "Moderate"
    )

st.success("✅ Good balance between recommendation quality and efficiency.")

st.divider()

# =====================================================
# Sentence-BERT
# =====================================================

st.header("🤖 Sentence-BERT")

st.info(
"""
**Sentence-BERT** converts each movie description into a dense semantic embedding.

Unlike traditional Bag-of-Words methods, it understands contextual meaning,
allowing it to recommend movies with similar themes even when they use different vocabulary.
"""
)

col1, col2 = st.columns(2)

with col1:

    st.metric(
        "Model Type",
        "Transformer"
    )

    st.metric(
        "Embedding Size",
        "384"
    )

with col2:

    st.metric(
        "Speed",
        "Moderate"
    )

    st.metric(
        "Semantic Understanding",
        "Excellent"
    )

st.success("✅ Produces the most relevant recommendations by understanding semantic similarity.")

st.divider()

# =====================================================
# Live Recommendation Comparison
# =====================================================

st.header("🎬 Live Recommendation Comparison")

st.markdown("""
Select a movie below to compare how each recommendation model performs.
This demonstrates the differences between **CountVectorizer**, **TF-IDF**, and **Sentence-BERT** on the same input.
""")

movie_list = sorted(df_master["movie_key"].dropna().unique())

movie = st.selectbox(
    "Choose a Movie",
    movie_list
)


if movie:

    col1, col2, col3 = st.columns(3)

    with col1:

        st.subheader("🔤 CountVectorizer")

        count_results = recommend_count(movie, 5)

        for i, (_, row) in enumerate(count_results.iterrows(), start=1):
            st.write(f"**{i}.** {row['title']}")

    with col2:

        st.subheader("📄 TF-IDF")

        tfidf_results = recommend_tfidf(movie, 5)

        for i, (_, row) in enumerate(tfidf_results.iterrows(), start=1):
            st.write(f"**{i}.** {row['title']}")

    with col3:

        st.subheader("🤖 Sentence-BERT")

        bert_results = recommend_bert(movie, 5)

        for i, (_, row) in enumerate(bert_results.iterrows(), start=1):
            st.write(f"**{i}.** {row['title']}")

st.divider()

